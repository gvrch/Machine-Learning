# 4. Fixed PID baseline
# ============================================================


class FixedPIDController:
    """Fixed-gain PID baseline for comparison."""

    def __init__(
        self,
        inertia: np.ndarray,
        wn: float = 0.08,
        zeta: float = 0.9,
        ki_ratio: float = 0.03,
        umax: float = 3e-4,
        integral_limit: float = 0.5,
        use_gyro_compensation: bool = True,
    ):
        self.I = np.asarray(inertia, dtype=float)
        self.umax = float(umax)
        self.integral_limit = float(integral_limit)
        self.use_gyro_compensation = bool(use_gyro_compensation)

        I_diag = np.diag(self.I)
        self.Kp = I_diag * wn**2
        self.Kd = 2.0 * zeta * I_diag * wn
        self.Ki = ki_ratio * self.Kp
        self.int_err = np.zeros(3)

    def reset(self):
        self.int_err = np.zeros(3)

    def __call__(self, obs: np.ndarray, dt: float = 0.1) -> np.ndarray:
        q = quat_normalize(obs[0:4])
        w = np.asarray(obs[4:7], dtype=float)
        e_q = np.sign(q[3] + 1e-12) * q[0:3]

        self.int_err = np.clip(
            self.int_err + e_q * dt,
            -self.integral_limit,
            self.integral_limit,
        )

        u = -self.Kp * e_q - self.Kd * w - self.Ki * self.int_err
        if self.use_gyro_compensation:
            u += np.cross(w, self.I @ w)
        return np.clip(u, -self.umax, self.umax)


