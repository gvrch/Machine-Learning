# 3. Gymnasium environment: PPO adaptive PID gain scheduler
# ============================================================


@dataclass
class GainBounds:
    P: Tuple[float, float] = (0.2, 3.0)
    D: Tuple[float, float] = (0.2, 3.0)
    I: Tuple[float, float] = (0.0, 2.0)


class CubeSatAdaptivePIDGainEnv(gym.Env):
    """
    Environment where the RL action adapts PID gain multipliers.

    Observation:
        obs = [q1, q2, q3, q4, wx, wy, wz, int_ex, int_ey, int_ez]

    Action:
        action = [aP, aD, aI] in [-1, 1]^3
    """

    metadata = {"render_modes": []}

    def __init__(
        self,
        inertia: Optional[np.ndarray] = None,
        dt: float = 0.1,
        max_time: float = 180.0,
        umax: float = 3e-4,
        random_initial_attitude: bool = True,
        random_initial_rate: bool = True,
        initial_angle_range_deg: Tuple[float, float] = (30.0, 150.0),
        w0_std_deg_s: float = 1.0,
        wn_nom: float = 0.08,
        zeta_nom: float = 0.9,
        ki_ratio_nom: float = 0.03,
        integral_limit: float = 0.5,
        gain_bounds: Optional[Dict[str, Tuple[float, float]]] = None,
        reward_weights: Optional[Dict[str, float]] = None,
        use_gyro_compensation: bool = True,
    ):
        super().__init__()

        if inertia is None:
            inertia = np.diag([0.058816667, 0.054000375, 0.011250375])

        self.I = np.asarray(inertia, dtype=float)
        self.dt = float(dt)
        self.max_time = float(max_time)
        self.max_steps = int(np.round(max_time / dt))
        self.umax = float(umax)

        self.random_initial_attitude = bool(random_initial_attitude)
        self.random_initial_rate = bool(random_initial_rate)
        self.initial_angle_range_deg = initial_angle_range_deg
        self.w0_std = np.deg2rad(w0_std_deg_s)
        self.use_gyro_compensation = bool(use_gyro_compensation)
        self.integral_limit = float(integral_limit)

        I_diag = np.diag(self.I)
        self.Kp_nom = I_diag * wn_nom**2
        self.Kd_nom = 2.0 * zeta_nom * I_diag * wn_nom
        self.Ki_nom = ki_ratio_nom * self.Kp_nom

        if gain_bounds is None:
            gain_bounds = {"P": (0.2, 3.0), "D": (0.2, 3.0), "I": (0.0, 2.0)}
        self.gain_bounds = gain_bounds

        if reward_weights is None:
            reward_weights = {
                "theta": 5.0,
                "omega": 0.2,
                "torque": 0.02,
                "integral": 0.02,
                "gain_rate": 0.01,
                "bonus_5deg": 2.0,
                "bonus_025deg": 8.0,
            }
        self.reward_weights = reward_weights

        high_obs = np.array(
            [1, 1, 1, 1, 10, 10, 10, integral_limit, integral_limit, integral_limit],
            dtype=np.float32,
        )
        self.observation_space = spaces.Box(low=-high_obs, high=high_obs, dtype=np.float32)
        self.action_space = spaces.Box(
            low=-np.ones(3, dtype=np.float32),
            high=np.ones(3, dtype=np.float32),
            dtype=np.float32,
        )

        self.x = np.zeros(7)
        self.int_err = np.zeros(3)
        self.t = 0.0
        self.step_count = 0
        self.prev_alpha = np.ones(3)

    @staticmethod
    def _scale_action(a: float, low: float, high: float) -> float:
        return low + 0.5 * (a + 1.0) * (high - low)

    def _map_action_to_gains(self, action: np.ndarray):
        action = np.clip(np.asarray(action, dtype=float).reshape(3), -1.0, 1.0)

        alphaP = self._scale_action(action[0], *self.gain_bounds["P"])
        alphaD = self._scale_action(action[1], *self.gain_bounds["D"])
        alphaI = self._scale_action(action[2], *self.gain_bounds["I"])
        alpha = np.array([alphaP, alphaD, alphaI])

        Kp = alphaP * self.Kp_nom
        Kd = alphaD * self.Kd_nom
        Ki = alphaI * self.Ki_nom
        return Kp, Kd, Ki, alpha

    def _get_obs(self) -> np.ndarray:
        return np.concatenate([self.x, self.int_err]).astype(np.float32)

    def reset(self, seed=None, options=None):
        super().reset(seed=seed)

        if self.random_initial_attitude:
            q0 = random_error_quaternion(*self.initial_angle_range_deg)
        else:
            q0 = quat_normalize(np.array([0.2226, 0.1019, -0.9678, 0.0589]))

        if self.random_initial_rate:
            w0 = np.random.normal(loc=0.0, scale=self.w0_std, size=3)
        else:
            w0 = np.zeros(3)

        self.x = np.concatenate([q0, w0]).astype(float)
        self.int_err = np.zeros(3)
        self.t = 0.0
        self.step_count = 0
        self.prev_alpha = np.ones(3)
        return self._get_obs(), {}

    def step(self, action: np.ndarray):
        Kp, Kd, Ki, alpha = self._map_action_to_gains(action)

        q = quat_normalize(self.x[0:4])
        w = self.x[4:7]
        q_vec = q[0:3]
        q4 = q[3]

        # Shortest-path quaternion vector error.
        e_q = np.sign(q4 + 1e-12) * q_vec

        # Integral term with anti-windup clipping.
        self.int_err = np.clip(
            self.int_err + e_q * self.dt,
            -self.integral_limit,
            self.integral_limit,
        )

        # Adaptive PID torque.
        u = -Kp * e_q - Kd * w - Ki * self.int_err
        if self.use_gyro_compensation:
            u += np.cross(w, self.I @ w)
        u = np.clip(u, -self.umax, self.umax)

        # Propagate dynamics.
        self.x = rk4_step(self.x, u, self.dt, self.I)
        self.t += self.dt
        self.step_count += 1

        q_next = self.x[0:4]
        w_next = self.x[4:7]
        theta_deg = pointing_error_deg(q_next)
        theta_rad = np.deg2rad(theta_deg)
        w_norm = np.linalg.norm(w_next)
        u_norm = np.linalg.norm(u)
        int_norm = np.linalg.norm(self.int_err)

        gain_rate_penalty = np.linalg.norm(alpha - self.prev_alpha) ** 2
        self.prev_alpha = alpha.copy()

        rw = self.reward_weights
        reward = (
            -rw["theta"] * theta_rad**2
            -rw["omega"] * w_norm**2
            -rw["torque"] * (u_norm / self.umax) ** 2
            -rw["integral"] * int_norm**2
            -rw["gain_rate"] * gain_rate_penalty
        )
        if theta_deg < 5.0:
            reward += rw["bonus_5deg"]
        if theta_deg < 0.25:
            reward += rw["bonus_025deg"]

        terminated = False
        truncated = self.step_count >= self.max_steps
        if w_norm > 1.0:
            terminated = True
            reward -= 50.0

        info = {
            "time": self.t,
            "theta_deg": theta_deg,
            "omega_norm": w_norm,
            "torque": u.copy(),
            "torque_norm": u_norm,
            "alphaP": alpha[0],
            "alphaD": alpha[1],
            "alphaI": alpha[2],
            "Kp": Kp.copy(),
            "Kd": Kd.copy(),
            "Ki": Ki.copy(),
            "integral_error": self.int_err.copy(),
        }
        return self._get_obs(), float(reward), terminated, truncated, info


