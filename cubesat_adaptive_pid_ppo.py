def _empty_history():
    return {
        "time": [],
        "theta_deg": [],
        "omega_norm": [],
        "torque": [],
        "reward": [],
        "q": [],
        "w": [],
        "alpha": [],
    }


def _history_to_arrays(hist: dict) -> dict:
    return {k: np.array(v) for k, v in hist.items()}


def rollout_fixed_pid(env: CubeSatAdaptivePIDGainEnv, controller: FixedPIDController) -> dict:
    """Rollout for fixed PID controller. It applies torque directly."""
    obs, _ = env.reset()
    controller.reset()
    hist = _empty_history()
    done = False

    while not done:
        u = controller(obs, dt=env.dt)

        env.x = rk4_step(env.x, u, env.dt, env.I)
        env.t += env.dt
        env.step_count += 1

        q = env.x[0:4]
        w = env.x[4:7]
        theta_deg = pointing_error_deg(q)
        theta_rad = np.deg2rad(theta_deg)
        w_norm = np.linalg.norm(w)
        u_norm = np.linalg.norm(u)

        rw = env.reward_weights
        reward = (
            -rw["theta"] * theta_rad**2
            -rw["omega"] * w_norm**2
            -rw["torque"] * (u_norm / env.umax) ** 2
        )
        if theta_deg < 5.0:
            reward += rw["bonus_5deg"]
        if theta_deg < 0.25:
            reward += rw["bonus_025deg"]

        terminated = w_norm > 1.0
        truncated = env.step_count >= env.max_steps
        if terminated:
            reward -= 50.0
        done = terminated or truncated

        obs = env._get_obs()

        hist["time"].append(env.t)
        hist["theta_deg"].append(theta_deg)
        hist["omega_norm"].append(w_norm)
        hist["torque"].append(u.copy())
        hist["reward"].append(float(reward))
        hist["q"].append(q.copy())
        hist["w"].append(w.copy())
        hist["alpha"].append([1.0, 1.0, 1.0])

    return _history_to_arrays(hist)


def rollout_adaptive_ppo(env: CubeSatAdaptivePIDGainEnv, model) -> dict:
    """Rollout for trained PPO gain scheduler."""
    obs, _ = env.reset()
    hist = _empty_history()
    done = False

    while not done:
        action, _ = model.predict(obs, deterministic=True)
        obs, reward, terminated, truncated, info = env.step(action)
        done = terminated or truncated

        hist["time"].append(info["time"])
        hist["theta_deg"].append(info["theta_deg"])
        hist["omega_norm"].append(info["omega_norm"])
        hist["torque"].append(info["torque"])
        hist["reward"].append(float(reward))
        hist["q"].append(obs[0:4].copy())
        hist["w"].append(obs[4:7].copy())
        hist["alpha"].append([info["alphaP"], info["alphaD"], info["alphaI"]])

    return _history_to_arrays(hist)


