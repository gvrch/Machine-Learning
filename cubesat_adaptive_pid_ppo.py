def compute_metrics(data: dict, threshold_deg: float = 5.0) -> dict:
    t = data["time"]
    theta = data["theta_deg"]
    w_norm = data["omega_norm"]
    torque = data["torque"]

    settling_time = np.nan
    if len(theta) > 0 and np.any(theta < threshold_deg):
        for k in range(len(theta)):
            if np.all(theta[k:] < threshold_deg):
                settling_time = t[k]
                break

    dt = np.mean(np.diff(t)) if len(t) > 1 else 0.0
    torque_norm = np.linalg.norm(torque, axis=1)

    return {
        "final_pointing_error_deg": float(theta[-1]),
        "max_pointing_error_deg": float(np.max(theta)),
        "final_omega_norm_rad_s": float(w_norm[-1]),
        "settling_time_5deg_s": float(settling_time) if np.isfinite(settling_time) else np.nan,
        "max_torque_Nm": float(np.max(np.abs(torque))),
        "torque_rms_Nm": float(np.sqrt(np.mean(torque_norm**2))),
        "torque_integral_Nm_s": float(np.sum(torque_norm) * dt),
        "total_reward": float(np.sum(data["reward"])),
    }


def print_metrics(name: str, metrics: dict) -> None:
    print(f"\n=== {name} metrics ===")
    for key, value in metrics.items():
        print(f"{key:30s}: {value:.6e}")


