def train_ppo_gain_scheduler(
    total_timesteps: int = 300_000,
    save_path: str = "results/ppo_adaptive_pid_gains",
):
    """Train PPO to adapt PID gain multipliers."""
    try:
        from stable_baselines3 import PPO
        from stable_baselines3.common.monitor import Monitor
        from stable_baselines3.common.vec_env import DummyVecEnv
    except ImportError as exc:
        raise ImportError(
            "Stable-Baselines3 is not installed. Install it with: "
            "pip install stable-baselines3"
        ) from exc

    def make_env():
        env = CubeSatAdaptivePIDGainEnv(
            dt=0.1,
            max_time=120.0,
            umax=3e-4,
            random_initial_attitude=True,
            random_initial_rate=True,
            initial_angle_range_deg=(30.0, 150.0),
            w0_std_deg_s=1.0,
            wn_nom=0.08,
            zeta_nom=0.9,
            ki_ratio_nom=0.03,
        )
        return Monitor(env)

    vec_env = DummyVecEnv([make_env])
    policy_kwargs = dict(net_arch=dict(pi=[64, 64], vf=[64, 64]))

    model = PPO(
        policy="MlpPolicy",
        env=vec_env,
        learning_rate=3e-4,
        n_steps=2048,
        batch_size=128,
        n_epochs=10,
        gamma=0.995,
        gae_lambda=0.95,
        clip_range=0.2,
        ent_coef=1e-3,
        policy_kwargs=policy_kwargs,
        verbose=1,
    )

    model.learn(total_timesteps=total_timesteps)
    os.makedirs(os.path.dirname(save_path), exist_ok=True)
    model.save(save_path)
    return model


