import numpy as np
from gymnasium import spaces


# ============================================================
# 1. Quaternion utilities
# ============================================================


def quat_normalize(q: np.ndarray) -> np.ndarray:
    q = np.asarray(q, dtype=float).reshape(4)
    n = np.linalg.norm(q)
    if n < 1e-12:
        return np.array([0.0, 0.0, 0.0, 1.0])
    return q / n


def quat_conjugate(q: np.ndarray) -> np.ndarray:
    q = quat_normalize(q)
    return np.array([-q[0], -q[1], -q[2], q[3]])


def quat_multiply(q: np.ndarray, p: np.ndarray) -> np.ndarray:
    """Hamilton product, scalar-last convention."""
    q = np.asarray(q, dtype=float).reshape(4)
    p = np.asarray(p, dtype=float).reshape(4)

    qx, qy, qz, qw = q
    px, py, pz, pw = p

    v = np.array([
        qw * px + pw * qx + qy * pz - qz * py,
        qw * py + pw * qy + qz * px - qx * pz,
        qw * pz + pw * qz + qx * py - qy * px,
    ])
    s = qw * pw - qx * px - qy * py - qz * pz

    return quat_normalize(np.array([v[0], v[1], v[2], s]))


def quat_from_axis_angle(axis: np.ndarray, angle_rad: float) -> np.ndarray:
    axis = np.asarray(axis, dtype=float).reshape(3)
    axis_norm = np.linalg.norm(axis)
    if axis_norm < 1e-12:
        axis = np.array([1.0, 0.0, 0.0])
    else:
        axis = axis / axis_norm

    q_vec = axis * np.sin(angle_rad / 2.0)
    q_sca = np.cos(angle_rad / 2.0)
    return quat_normalize(np.array([q_vec[0], q_vec[1], q_vec[2], q_sca]))


def random_error_quaternion(
    min_angle_deg: float = 30.0,
    max_angle_deg: float = 150.0,
) -> np.ndarray:
    """Random attitude error sampled through axis-angle."""
    axis = np.random.normal(size=3)
    axis = axis / (np.linalg.norm(axis) + 1e-12)
    angle = np.deg2rad(np.random.uniform(min_angle_deg, max_angle_deg))
    return quat_from_axis_angle(axis, angle)


def pointing_error_deg(q_err: np.ndarray) -> float:
    """Pointing error theta = 2 acos(|q4|), returned in degrees."""
    q_err = quat_normalize(q_err)
    q4 = np.clip(np.abs(q_err[3]), 0.0, 1.0)
    theta = 2.0 * np.arccos(q4)
    return float(np.rad2deg(theta))


def omega_matrix(w: np.ndarray) -> np.ndarray:
    """Omega(w) matrix for scalar-last quaternion q_dot = 0.5 Omega(w) q."""
    wx, wy, wz = np.asarray(w, dtype=float).reshape(3)
    return np.array([
        [0.0, wz, -wy, wx],
        [-wz, 0.0, wx, wy],
        [wy, -wx, 0.0, wz],
        [-wx, -wy, -wz, 0.0],
    ])


# ============================================================
# 2. Rigid-body dynamics
# ============================================================


def rigid_body_derivative(x: np.ndarray, u: np.ndarray, inertia: np.ndarray) -> np.ndarray:
    """State x = [q1, q2, q3, q4, wx, wy, wz]."""
    x = np.asarray(x, dtype=float).reshape(7)
    u = np.asarray(u, dtype=float).reshape(3)

    q = quat_normalize(x[0:4])
    w = x[4:7]

    Iw = inertia @ w
    q_dot = 0.5 * omega_matrix(w) @ q
    w_dot = np.linalg.solve(inertia, u - np.cross(w, Iw))

    return np.concatenate([q_dot, w_dot])


def rk4_step(x: np.ndarray, u: np.ndarray, dt: float, inertia: np.ndarray) -> np.ndarray:
    k1 = rigid_body_derivative(x, u, inertia)
    k2 = rigid_body_derivative(x + 0.5 * dt * k1, u, inertia)
    k3 = rigid_body_derivative(x + 0.5 * dt * k2, u, inertia)
    k4 = rigid_body_derivative(x + dt * k3, u, inertia)

    x_next = x + (dt / 6.0) * (k1 + 2.0 * k2 + 2.0 * k3 + k4)
    x_next[0:4] = quat_normalize(x_next[0:4])
    return x_next


