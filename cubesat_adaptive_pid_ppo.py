"""
CubeSat attitude control with PPO adaptive PID gain scheduling.

Purpose
-------
This script implements a simplified rigid-body CubeSat attitude model and compares:

1) Fixed PID baseline
2) PPO adaptive PID gain scheduler

The PPO agent does NOT command the reaction-wheel torque directly.
Instead, it commands normalized gain multipliers:

    action = [aP, aD, aI] in [-1, 1]^3

which are mapped to:

    Kp(t) = alphaP(t) * Kp_nom
    Kd(t) = alphaD(t) * Kd_nom
    Ki(t) = alphaI(t) * Ki_nom

The physical torque is still generated by an interpretable quaternion PID law:

    u = -Kp(t) * sign(q4) * q_vec
        -Kd(t) * omega
        -Ki(t) * integral(sign(q4) * q_vec)
        + omega x I omega

Dynamics
--------
    I * omega_dot = u - omega x (I omega)
    q_dot = 0.5 * Omega(omega) q

Quaternion convention
---------------------
Scalar-last quaternion:
    q = [q1, q2, q3, q4]

Run
---
    python cubesat_adaptive_pid_ppo.py

By default, PPO training is OFF so the script runs immediately.
Set TRAIN_RL = True in main() to train the adaptive gain scheduler.
"""

from __future__ import annotations

